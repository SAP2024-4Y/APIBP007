CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE restaurant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    description TEXT,
    cuisine VARCHAR(80) NOT NULL,
    address VARCHAR(300) NOT NULL,
    city VARCHAR(100) NOT NULL,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    price_level SMALLINT NOT NULL DEFAULT 2 CHECK (price_level BETWEEN 1 AND 4),
    average_rating NUMERIC(2,1) NOT NULL DEFAULT 0 CHECK (average_rating BETWEEN 0 AND 5),
    booking_url VARCHAR(500),
    image_url VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT restaurant_coordinates_together CHECK ((latitude IS NULL) = (longitude IS NULL))
);
CREATE INDEX idx_restaurant_city ON restaurant (city);
CREATE INDEX idx_restaurant_cuisine ON restaurant (cuisine);
CREATE INDEX idx_restaurant_active ON restaurant (active);

CREATE TABLE menu_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurant(id) ON DELETE CASCADE,
    name VARCHAR(160) NOT NULL,
    description TEXT,
    category VARCHAR(80),
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    vegetarian BOOLEAN NOT NULL DEFAULT FALSE,
    available BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_menu_item_restaurant ON menu_item (restaurant_id, available);

CREATE TABLE review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurant(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_review_restaurant ON review (restaurant_id);

-- Each slot is one bookable start time. Capacity is tracked in people, which
-- supports groups rather than counting each reservation as one seat.
CREATE TABLE reservation_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurant(id) ON DELETE CASCADE,
    starts_at TIMESTAMPTZ NOT NULL,
    duration_minutes SMALLINT NOT NULL DEFAULT 120 CHECK (duration_minutes BETWEEN 30 AND 360),
    capacity_people INTEGER NOT NULL CHECK (capacity_people > 0),
    reserved_people INTEGER NOT NULL DEFAULT 0 CHECK (reserved_people >= 0 AND reserved_people <= capacity_people),
    UNIQUE (restaurant_id, starts_at)
);
CREATE INDEX idx_reservation_slot_lookup ON reservation_slot (restaurant_id, starts_at);

CREATE TABLE reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL REFERENCES reservation_slot(id),
    user_id BIGINT REFERENCES app_user(id) ON DELETE SET NULL,
    guest_name VARCHAR(120) NOT NULL,
    guest_email VARCHAR(255) NOT NULL,
    party_size SMALLINT NOT NULL CHECK (party_size BETWEEN 1 AND 30),
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    special_request VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reservation_slot_status ON reservation (slot_id, status);
